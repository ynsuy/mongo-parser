#!/usr/bin/env python3
"""Writes the label review workbook from the parser's rule book.

    python3 scripts/labels-review.py [parser binary] [output .xlsx]

Defaults: bin/mongo-log-parser and ../docs/labels-review.xlsx, relative to the parser directory.
Needs openpyxl. Rebuild the parser first: the workbook is whatever rules the binary was built with.
"""
import json, os, subprocess, sys
from openpyxl import Workbook
from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
from openpyxl.utils import get_column_letter

here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
binary = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'bin', 'mongo-log-parser')
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', 'docs', 'labels-review.xlsx')
rules = json.loads(subprocess.run([binary, 'labels', '--json'], check=True, capture_output=True, text=True).stdout)['data']

def degree(l, v):
    def ramp(a, b):
        return 0 if v <= a else 1 if v >= b else (v - a) / (b - a)
    if l.get('up'): return ramp(*l['up'])
    if l.get('down'): return 1 - ramp(*l['down'])
    b = l['band']
    return ramp(b[0], b[1]) if v < b[1] else 1 - ramp(b[2], b[3])

def example(rule):
    """A value between the two lowest bands, read as the rule reads it: fuzzy, by degree."""
    levels = rule.get('levels') or []
    if len(levels) < 2:
        return ''
    lo, hi = levels[0], levels[1]
    fade = lo['down'][1] if lo.get('down') else lo['band'][3]
    rise = hi['up'][0] if hi.get('up') else hi['band'][0]
    v = round((fade + rise) / 2, 3)
    parts = [f"{round(degree(l, v)*100)}% {l['name']}" for l in levels if degree(l, v) > 0]
    return f"{v:g} {rule['unit']} → " + ", ".join(parts)

def open_from(rule):
    levels = rule.get('levels') or []
    if not levels: return 'shape only: a step, an episode, a schedule'
    if rule.get('open_at'): return f"{rule['open_at']} and above (set by the rule)"
    names = [l['name'] for l in levels]
    return ' or '.join(names[-2:] if len(names) >= 4 else names[-1:])

def mark(rule):
    if rule.get('elevated') is None: return ''
    word = 'or less' if rule.get('direction') == 'down' else 'or more'
    return f"{rule['elevated']:g} {rule['unit']} {word}"

font = Font(name='Arial', size=10)
bold = Font(name='Arial', size=10, bold=True, color='FFFFFF')
head_fill = PatternFill('solid', fgColor='1F4E78')
wrap = Alignment(wrap_text=True, vertical='top')
thin = Side(style='thin', color='D9D9D9')
grid = Border(left=thin, right=thin, top=thin, bottom=thin)

wb = Workbook()
guide = wb.active
guide.title = 'How to read'
lines = [
    ('What this is', 'Every label mongo-log-parser can put on a bundle, one row per definition. A label renamed between server versions has a row per version range. Generated by mongo-log-parser/scripts/labels-review.py from `mongo-log-parser labels --json`; the rules themselves are mongo-log-parser/internal/label/rules/*.yaml.'),
    ('What a label is for', 'Labels are where an investigation starts. The report lays every label of every node out as worth opening, worth noticing, or ordinary; `mongo-log-parser label <bundle> <label> --source <node>` opens one: the exact seconds it was past its mark, the labels it pairs with over those seconds, and the node\'s log in the same window.'),
    ('One second', 'FTDC samples about once a second. "What one second is" is the formula for each sample. Δ is a counter read as its change a second.'),
    ('Read on', 'Each minute keeps its mean, its highest and lowest second, and — for a rule with a threshold — how many seconds were past it. "Read on" is the summary the bands and the shape use. A burst that a minute mean would hide (a ticket pool empty for ten seconds) is counted in seconds (s/min) instead.'),
    ('Bands', 'Fuzzy: a value near an edge belongs to two bands by degree. "Example" shows one such value.'),
    ('Worth opening from', 'The band from which the label is listed as worth opening. The default is the top two bands of four or more, the top band otherwise; a rule can lower it (a single second with no ticket left is worth opening).'),
    ('Duty mark', 'Minutes at or past this value count towards the duty cycle: how much of the window the label spent somewhere it should not stay. More than a rare minute past it also makes a label worth opening.'),
    ('Min change', 'The smallest move, in the label\'s unit, that counts as a step, an episode or a trend.'),
    ('Pairs with', 'The labels read beside this one, over the same seconds, when it is opened.'),
]
guide.column_dimensions['A'].width = 22
guide.column_dimensions['B'].width = 120
for i, (k, v) in enumerate(lines, start=1):
    guide.cell(i, 1, k).font = Font(name='Arial', size=10, bold=True)
    c = guide.cell(i, 2, v); c.font = font; c.alignment = wrap
    guide.cell(i, 1).alignment = wrap

ws = wb.create_sheet('Labels')
cols = [
    ('Subject', 14, lambda r: r['pack']),
    ('Label', 26, lambda r: r['name']),
    ('Title', 30, lambda r: r['title']),
    ('Server versions', 16, lambda r: r['version_text']),
    ('What it means', 60, lambda r: ' '.join(r['doc'].split())),
    ('What one second is', 50, lambda r: r['formula']),
    ('Read on', 28, lambda r: r['reading']),
    ('Unit', 10, lambda r: r['unit']),
    ('Bands', 44, lambda r: r['bands']),
    ('Example', 30, example),
    ('Worth opening from', 22, open_from),
    ('Duty mark', 16, mark),
    ('Min change', 12, lambda r: f"{r['min_change']:g} {r['unit']}"),
    ('Pairs with', 34, lambda r: ', '.join(r.get('pairs_with') or [])),
]
for j, (title, width, _) in enumerate(cols, start=1):
    c = ws.cell(1, j, title); c.font = bold; c.fill = head_fill; c.alignment = wrap; c.border = grid
    ws.column_dimensions[get_column_letter(j)].width = width
for i, r in enumerate(rules, start=2):
    for j, (_, _, read) in enumerate(cols, start=1):
        c = ws.cell(i, j, read(r)); c.font = font; c.alignment = wrap; c.border = grid
ws.freeze_panes = 'C2'
ws.auto_filter.ref = f"A1:{get_column_letter(len(cols))}{len(rules)+1}"
wb.save(out)
print(len(rules), 'rows')
